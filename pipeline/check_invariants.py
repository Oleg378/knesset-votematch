"""Invariants of the quiz data (customer 2026-10-21, after the cycle «dropped bills → new themes → new statements»). Run after every stage
that changes labels, themes or statements, and before every release: `make check`. Exit code 1 on any FAIL.

  I1  every statement's theme passes the selection (pipeline/quiz_select.py)          — a failing statement is removed (customer rule)
  I2  one theme — one statement
  I3  no statement on a remainder of a split theme or on a technical theme
  I4  every theme that passes the selection and has no statement has a decision in data/directions/registry.csv
      (duplicate / split / basket / technical / no_statement / dropped_dup); «pending» is a WARN
  I5  no two statement themes nested: the smaller shares < 50 % of its bills (by name, ≥ 5 shared) with the other
  I6  every bill label on a statement theme was label-checked (data/directions/labels/label_check_coverage.csv; a check under the theme
      a part was split from counts)
  I7  the export holds exactly the current statements (ids, texts, keys)
  I8  export/quiz_texts.json (every user-facing text, edited by hand) validates against export/quiz_texts.schema.json
      (generated by the web side: structure, allowed placeholders); a missing schema is a WARN
  I9  the numbers typed in the documents (docs/TECHNICAL.md, export/WEB_CONTRACT.md) match export/stats.json: counts exactly,
      file sizes within 15 %
  I10 export/golden.json is current: the golden cases recomputed as pipeline/export.py does give the same ranking, notes and
      explanation lines
"""
import csv, json, os, re, sys, itertools, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "pipeline"))
import labels as LB, quiz_select as QS
import duckdb
fails, warns = [], []
def fail(code, msg): fails.append(f"FAIL {code}: {msg}")
def warn(code, msg): warns.append(f"WARN {code}: {msg}")

C = QS.criteria()
st = [r for r in csv.DictReader(open(f"{ROOT}/data/quiz/statements.csv")) if r["status"] == "ok"]
by_d = collections.defaultdict(list)
for r in st: by_d[r["d"]].append(r)
reg = {r["d"]: r for r in csv.DictReader(open(f"{ROOT}/data/directions/registry.csv"))}
lab = LB.load(); bl = lab["bill_lab"]
pl = json.load(open(f"{ROOT}/data/directions/split/plan.json"))
rem = (set(pl["parents"]) - set(pl["keep"])) | {d for p in LB.later_plans() for d in p["parents"]}
tech = {d for d, r in reg.items() if r["status"] == "technical"}

for r in st:                                                                       # I1
    x = C.get(r["d"]) or {}
    if not x.get("base"): fail("I1", f"q{r['q']} «{r['title_en']}» ({r['d']}): lists {x.get('lists')}, SD {x.get('sd', 0):.2f}, names {x.get('nA')}")
for d, rs in by_d.items():                                                         # I2
    if len(rs) > 1: fail("I2", f"theme {d} has {len(rs)} statements: " + ", ".join("q" + r["q"] for r in rs))
for r in st:                                                                       # I3
    if r["d"] in rem: fail("I3", f"q{r['q']} on remainder {r['d']}")
    if r["d"] in tech: fail("I3", f"q{r['q']} on technical theme {r['d']}")
OK = {"duplicate", "split", "basket", "technical", "no_statement", "dropped_dup"}
for d, x in C.items():                                                             # I4
    if not x["base"] or d in by_d or d in rem: continue
    s = (reg.get(d) or {}).get("status")
    if s == "pending": warn("I4", f"{d} «{x['name'][:50]}» is in the procedure (pending)")
    elif s not in OK: fail("I4", f"{d} «{x['name'][:50]}» passes the selection, has no statement and no registry decision")
con = duckdb.connect(f"{ROOT}/knesset.duckdb", read_only=True)                     # I5
base = lambda n: re.sub(r",?\s*(ה?תש[\"״׳'\w\-]*\s*-?\s*\d{4})\s*$", "", str(n or "")).strip()
bn = {b: base(n) for b, n in con.execute("select bill_id, name from bills where knesset in (24, 25)").fetchall()}
nm = collections.defaultdict(set)
for b, lb in bl.items():
    if b in bn:
        for d in LB.signed_topics(lb):
            if d in by_d: nm[d].add(bn[b])
for a, b in itertools.combinations(by_d, 2):
    s = nm[a] & nm[b]; m = min(len(nm[a]), len(nm[b]))
    if m and len(s) >= 5 and len(s) / m >= 0.5:
        fail("I5", f"q{by_d[a][0]['q']} ({a}, {len(nm[a])}) and q{by_d[b][0]['q']} ({b}, {len(nm[b])}) share {len(s)} — {len(s)/m:.0%} of the smaller")
cov = {(r["bill_id"], r["d"]) for r in csv.DictReader(open(f"{ROOT}/data/directions/labels/label_check_coverage.csv"))}   # I6
parent = {}
for p, subs in lab["split_plan"]["parents"].items():
    for s in subs: parent.setdefault(s, p)
def lineage(d):
    out = [d]
    while d in parent and parent[d] not in out: d = parent[d]; out.append(d)
    return out
un = collections.Counter()
for b, lb in bl.items():
    for d in LB.signed_topics(lb):
        if d in by_d and not any((str(b), x) in cov for x in lineage(d)): un[d] += 1
for d, n in un.items(): fail("I6", f"q{by_d[d][0]['q']} ({d}): {n} bill labels never label-checked")
ex = {s["q"]: s for s in json.load(open(f"{ROOT}/export/quiz_data.json"))["statements"]}   # I7
cur = {r["q"]: r for r in st}
for q in set(ex) ^ set(cur): fail("I7", f"q{q} is {'only in the export' if q in ex else 'not in the export'} (run make data)")
for q in set(ex) & set(cur):
    if ex[q]["statement_en"] != cur[q]["statement_en"] or int(ex[q]["key"]) != (1 if cur[q]["agree_key"] == "+" else -1): fail("I7", f"q{q}: export text or key differs (run make data)")

try:                                                                               # I8
    import jsonschema
    sch = f"{ROOT}/export/quiz_texts.schema.json"
    if not os.path.exists(sch): warn("I8", "schema not generated yet (cd web && npm run schema:texts)")
    else: jsonschema.validate(json.load(open(f"{ROOT}/export/quiz_texts.json")), json.load(open(sch)))
except jsonschema.ValidationError as e:
    fail("I8", f"export/quiz_texts.json: {e.message[:200]} at {'/'.join(map(str, e.absolute_path))}")

stats = json.load(open(f"{ROOT}/export/stats.json"))                              # I9
num = lambda x: int(re.sub(r"\s", "", x))
def typed(doc, pattern, phrase, real, tol=0.0, scale=1.0, conv=num):
    m = re.search(pattern, open(f"{ROOT}/{doc}").read())
    if not m: return fail("I9", f"{doc}: phrase «{phrase}» not found")
    for g, r in zip(m.groups(), real if isinstance(real, tuple) else (real,)):
        v = conv(g) * scale
        if (abs(v - r) > tol * r) if tol else v != r:
            fail("I9", f"{doc}: «{phrase}» says {g.strip()}, export/stats.json has {r if scale == 1 else r / scale}")
Ls = stats["lists"]
typed("docs/TECHNICAL.md", r"вопросов — (\d+)", "вопросов — N", stats["statements"])
typed("docs/TECHNICAL.md", r"Списков: (\d+) оцениваются, (\d+) с одним бывшим депутатом не ранжируются, (\d+) без истории",
      "Списков: N оцениваются, N с одним бывшим депутатом не ранжируются, N без истории", (Ls["evaluated"], Ls["warning"], Ls["no_record"]))
typed("docs/TECHNICAL.md", r"Законопроектов в экспорте — ([\d\s]+?)\.", "Законопроектов в экспорте — N", stats["bills"])
F = stats["files"]
typed("export/WEB_CONTRACT.md", r"\| `quiz_data.json` \| ~(\d+) KB", "quiz_data.json ~N KB", F["quiz_data.json"], tol=0.15)
typed("export/WEB_CONTRACT.md", r"\| `quiz_bills.json` \| ~([\d.]+) MB", "quiz_bills.json ~N MB", F["quiz_bills.json"], tol=0.15, scale=1000, conv=float)
typed("export/WEB_CONTRACT.md", r"\| `quiz_core.json` \| ~(\d+) KB", "quiz_core.json ~N KB", F["quiz_core.json"], tol=0.15)

import export as EX, quiz_report as QR                                            # I10
gold = {c["name"]: c for c in json.load(open(f"{ROOT}/export/golden.json"))["cases"]}
new = {c["name"]: c for c in EX.golden(QR.context())["cases"]}
close = lambda x, y: x == y or (x is not None and y is not None and abs(x - y) <= 1e-9)
stale = sorted(set(gold) ^ set(new))
for n in set(gold) & set(new):
    a, b = gold[n], new[n]
    ra = [(r["id"], r["ranked"], r["note"]) for r in a["ranking"]]; rb = [(r["id"], r["ranked"], r["note"]) for r in b["ranking"]]
    if (ra != rb or not all(close(x["closeness"], y["closeness"]) and close(x["coverage"], y["coverage"]) for x, y in zip(a["ranking"], b["ranking"]))
            or [[(i["q"], i["lines"]) for i in d["items"]] for d in a["details"]] != [[(i["q"], i["lines"]) for i in d["items"]] for d in b["details"]]):
        stale.append(n)
if stale: fail("I10", f"export/golden.json differs from the current reference in {len(stale)} case(s) ({', '.join(stale[:3])}…): run make data")

print(f"{len(st)} statements, {len(C)} themes with positions, {len(reg)} registry rows")
for l in fails + warns: print(l)
print("OK" if not fails else f"{len(fails)} FAIL, {len(warns)} WARN")
sys.exit(1 if fails else 0)
